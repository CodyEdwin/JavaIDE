package dev.javaide.gradlebridge;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates the temporary init script for one test run.
 *
 * <p>Tests run through {@link org.gradle.tooling.BuildLauncher}, not
 * {@code TestLauncher}: Gradle's {@code TestExecutionBuildConfigurationAction}
 * always calls {@code test.debugOptions { enabled = false }} for a
 * {@code TestLauncher} run unless {@code debugTestsOn} is used, which overrides
 * any debug options configured by an init script. {@code debugTestsOn} uses
 * {@code server=false}, which expects the debugger to listen; java-debug
 * attaches as a client. A normal build launcher preserves the script's
 * {@code server=true} settings.
 *
 * <p>The Tooling API rejects {@code --tests} as a build argument, so test
 * selection is configured here with the same calls Gradle uses internally:
 * {@code TestFilter.includeTest(className, methodName)} and
 * {@code setFailOnNoMatchingTests(false)}. The script also disables up-to-date
 * checks and build-cache hits for test tasks: running tests from the IDE must
 * execute them, because a replayed result produces no test events and, for a
 * debug run, no JDWP listener.
 */
final class TestRunScript {
    record DebugOptions(String host, int port, boolean suspend) {}

    record TestRef(String className, String methodName) {}

    private TestRunScript() {}

    /** Writes a script for the selected task and tests. */
    static Path write(
            String taskPath,
            List<String> classes,
            List<TestRef> methods,
            DebugOptions debug)
            throws IOException {
        String path = taskPath == null || taskPath.isBlank() ? ":" : taskPath;
        if (!path.startsWith(":")) {
            throw new IllegalArgumentException("task path must start with ':': " + path);
        }

        StringBuilder filter = new StringBuilder();
        if (!classes.isEmpty() || !methods.isEmpty()) {
            filter.append("            testTask.filter {\n")
                    .append("                setFailOnNoMatchingTests(false)\n");
            for (String className : classes) {
                filter.append("                includeTest('")
                        .append(escape(className))
                        .append("', null)\n");
            }
            for (TestRef method : methods) {
                filter.append("                includeTest('")
                        .append(escape(method.className()))
                        .append("', '")
                        .append(escape(method.methodName()))
                        .append("')\n");
            }
            filter.append("            }\n");
        }

        String debugBlock = "";
        if (debug != null) {
            String host = debug.host() == null || debug.host().isBlank()
                    ? "127.0.0.1"
                    : debug.host();
            if (!host.equals("127.0.0.1") && !host.equals("localhost") && !host.equals("::1")) {
                throw new IllegalArgumentException("debug host must be loopback: " + host);
            }
            if (debug.port() < 1 || debug.port() > 65_535) {
                throw new IllegalArgumentException("debug port is out of range: " + debug.port());
            }
            debugBlock = """
                            testTask.debugOptions {
                                enabled = true
                                host = '%s'
                                port = %d
                                server = true
                                suspend = %s
                            }
                            // A suspended worker plus parallel forks deadlocks the run.
                            testTask.maxParallelForks = 1
                            testTask.forkEvery = 0
                    """.formatted(escape(host), debug.port(), debug.suspend());
        }

        String script = """
                // Generated by JavaIDE for one test run. Do not put this in the project.
                gradle.beforeProject { project ->
                    project.tasks.withType(org.gradle.api.tasks.testing.Test).configureEach { testTask ->
                        if (testTask.path == '%s') {
                %s        }
                        // The IDE must execute the selected tests, not replay cached results.
                        testTask.outputs.upToDateWhen { false }
                        testTask.outputs.cacheIf { false }
                %s    }
                }
                """.formatted(escape(path), filter, debugBlock);
        Path file = Files.createTempFile("javaide-test-run-", ".gradle");
        Files.writeString(file, script, StandardCharsets.UTF_8);
        return file;
    }

    private static String escape(String value) {
        return value.replace("\\", "\\\\").replace("'", "\\'");
    }
}
